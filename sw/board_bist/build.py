#!/usr/bin/env python3
"""
sw/board_bist/build.py — 零外部工具链生成 Nexys 4 DDR 100 MHz 实板上电自检 BootROM 镜像
--------------------------------------------------------------------------------
基于仓库自带 tools/asm.py 汇编生成精确 4,096 字 (16 KB) 的 board_bist.hex，供 Vivado
综合时经 `ROM_INIT_FILE="board_bist.hex"` 烧入 rtl/soc/bootrom.v，也可在仿真中经
`+rom=sw/board_bist/board_bist.hex` 独立回归验证。

上电自动测试序列 (100 MHz SoC + 115200 8N1 UART):
  1) 128 MB DDR2 跨区读写校验 (0x8000_0000 .. 0x87FF_F000 共 8 个边界点)
  2) 16 KB (2x L1D 容量) 连续写回驱逐 + 128-bit 读行缓冲回读校验
  3) 128-bit 突发块全 4 个 lane 字节/半字掩码 (SB/SH/LBU/LHU) 校验
  4) DDR2 自修改代码 + FENCE.I 闭环执行 (验证 D$ 清洗 + I$ 64B 重填 + BTB + RAS)
  5) CPU 性能计数自检 (mcycle / minstret / CLINT 1 MHz mtime 互证 100 MHz 主频)
  6) 外设自检: VGA 分辨率 ID (640x480 彩条开启)、microSD 插卡状态、OV5640 SCCB ID 探测
  7) 进入串口交互控制台: [t]重测DDR2  [b]CPU基准  [c]探OV5640  [s]外设状态  [?]帮助
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import asm  # noqa: E402

BOOTROM_BASE = 0x00001000
BOOTROM_WORDS = 4096  # 16 KB
NOP_WORD = 0x00000013


def build_asm_source() -> str:
    strings = {
        "str_banner": "\r\n=== NEXYS4 RV32IMA 100MHz BRINGUP ===\r\n",
        "str_t1": "[1/5] DDR2 128MB span + 16KB evict + mask + SMC: ",
        "str_pass": "PASS\r\n",
        "str_fail": "FAIL code=",
        "str_t2": "[2/5] Bench CYC=",
        "str_ins": " INS=",
        "str_mt": " MTIME=",
        "str_t3": "[3/5] VGA ID=",
        "str_fr": " FR=",
        "str_t4": "[4/5] SD_CD=",
        "str_sd_in": "INSERTED\r\n",
        "str_sd_no": "EMPTY\r\n",
        "str_t5": "[5/5] OV5640 SCCB ",
        "str_cam_ok": "ID=",
        "str_cam_no": "NACK(absent)\r\n",
        "str_done": "READY! Cmd: [t]DDR2 [b]Bench [c]Cam [s]Stat\r\n",
        "str_nl": "\r\n",
        "str_prompt": "> ",
    }

    lines = [
        f".org 0x{BOOTROM_BASE:08x}",
        "_start:",
        "  # 设置栈指针到 DDR2 高端临时安全区 (仅用于需要子程序嵌套时，此处全程使用寄存器+s区不依赖DDR2即可串口打印)",
        "  li s0, 0x10000000       # s0 = UART_BASE (NS16550A)",
        "  li a0, str_banner",
        "  jal ra, uart_puts",
        "  jal ra, run_all_tests",
        "",
        "cmd_loop:",
        "  li a0, str_prompt",
        "  jal ra, uart_puts",
        "cmd_wait:",
        "  lw t0, 20(s0)           # UART_LSR (+0x14)",
        "  andi t0, t0, 1          # bit0 = RX_DR",
        "  beq t0, zero, cmd_wait",
        "  lw s1, 0(s0)            # 读接收字节",
        "  andi s1, s1, 0xFF",
        "  mv a0, s1",
        "  jal ra, uart_putc       # 串口回显",
        "  li a0, str_nl",
        "  jal ra, uart_puts",
        "  li t0, 116              # 't' -> DDR2 test",
        "  beq s1, t0, do_cmd_t",
        "  li t0, 98               # 'b' -> Bench",
        "  beq s1, t0, do_cmd_b",
        "  li t0, 99               # 'c' -> Cam ID",
        "  beq s1, t0, do_cmd_c",
        "  li t0, 115              # 's' -> Status",
        "  beq s1, t0, do_cmd_s",
        "  li a0, str_done",
        "  jal ra, uart_puts",
        "  j cmd_wait",
        "",
        "do_cmd_t:",
        "  jal ra, test_ddr2",
        "  j cmd_loop",
        "do_cmd_b:",
        "  jal ra, test_bench",
        "  j cmd_loop",
        "do_cmd_c:",
        "  jal ra, test_cam",
        "  j cmd_loop",
        "do_cmd_s:",
        "  jal ra, test_vga_sd",
        "  j cmd_loop",
        "",
        "# ======================================================================",
        "# 自动全套上电自检 (s11 保存返回地址)",
        "# ======================================================================",
        "run_all_tests:",
        "  mv s11, ra",
        "  jal ra, test_ddr2",
        "  jal ra, test_bench",
        "  jal ra, test_vga_sd",
        "  jal ra, test_cam",
        "  li a0, str_done",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s11)",
        "",
        "# ======================================================================",
        "# [1/5] 128 MB DDR2 跨区 + 16 KB D-Cache 驱逐 + 字节掩码 + SMC FENCE.I",
        "# ======================================================================",
        "test_ddr2:",
        "  mv s10, ra",
        "  li a0, str_t1",
        "  jal ra, uart_puts",
        "",
        "  # 1A) 128 MB 全空间 8 个边界点写入与回读",
        "  li s2, ddr_span_tbl",
        "  li s3, 8",
        "  li s4, 0xA55A0001",
        "span_wr_loop:",
        "  lw t0, 0(s2)",
        "  sw s4, 0(t0)",
        "  addi s2, s2, 4",
        "  addi s4, s4, 0x111",
        "  addi s3, s3, -1",
        "  bne s3, zero, span_wr_loop",
        "",
        "  li s2, ddr_span_tbl",
        "  li s3, 8",
        "  li s4, 0xA55A0001",
        "span_rd_loop:",
        "  lw t0, 0(s2)",
        "  lw t1, 0(t0)",
        "  li a0, 1",
        "  bne t1, s4, ddr2_fail",
        "  addi s2, s2, 4",
        "  addi s4, s4, 0x111",
        "  addi s3, s3, -1",
        "  bne s3, zero, span_rd_loop",
        "",
        "  # 1B) 16 KB 连续写回驱逐 (4096 字 = 2x L1D 容量, 强压 100<->75 MHz FIFO)",
        "  li t0, 0x80020000",
        "  li t1, 4096",
        "  li t2, 0x13570000",
        "evict_wr:",
        "  sw t2, 0(t0)",
        "  addi t0, t0, 4",
        "  addi t2, t2, 0x101",
        "  addi t1, t1, -1",
        "  bne t1, zero, evict_wr",
        "",
        "  li t0, 0x80020000",
        "  li t1, 4096",
        "  li t2, 0x13570000",
        "evict_rd:",
        "  lw t3, 0(t0)",
        "  li a0, 2",
        "  bne t3, t2, ddr2_fail",
        "  addi t0, t0, 4",
        "  addi t2, t2, 0x101",
        "  addi t1, t1, -1",
        "  bne t1, zero, evict_rd",
        "",
        "  # 1C) 128-bit 行内全 4 lane 字节/半字写掩码 (SB/SH/LW 校验)",
        "  li t0, 0x80001000",
        "  li t1, 0x11223344",
        "  sw t1, 0(t0)",
        "  sw t1, 4(t0)",
        "  sw t1, 8(t0)",
        "  sw t1, 12(t0)",
        "  li t2, 0xAA",
        "  sb t2, 1(t0)            # lane0 -> 0x1122AA44",
        "  li t2, 0xBBCC",
        "  sh t2, 6(t0)            # lane1 -> 0xBBCC3344",
        "  li t2, 0xDD",
        "  sb t2, 11(t0)           # lane2 -> 0xDD223344",
        "  li t2, 0xEE",
        "  sb t2, 12(t0)           # lane3 -> 0x112233EE",
        "  lw t3, 0(t0)",
        "  li t4, 0x1122AA44",
        "  li a0, 3",
        "  bne t3, t4, ddr2_fail",
        "  lw t3, 4(t0)",
        "  li t4, 0xBBCC3344",
        "  li a0, 4",
        "  bne t3, t4, ddr2_fail",
        "  lw t3, 8(t0)",
        "  li t4, 0xDD223344",
        "  li a0, 5",
        "  bne t3, t4, ddr2_fail",
        "  lw t3, 12(t0)",
        "  li t4, 0x112233EE",
        "  li a0, 6",
        "  bne t3, t4, ddr2_fail",
        "",
        "  # 1D) DDR2 自修改代码 + FENCE.I (验证 D$ 清洗 + I$ 64B 填充 + 32-bit BTB + RAS)",
        "  li t0, 0x80002000",
        "  li t1, 0x02A50513       # addi a0, a0, 42",
        "  sw t1, 0(t0)",
        "  li t1, 0x00008067       # jalr zero, 0(ra) (ret)",
        "  sw t1, 4(t0)",
        "  .word 0x0000100F        # fence.i",
        "  li a0, 100",
        "  jalr ra, 0(t0)",
        "  li t1, 142",
        "  li a0, 7",
        "  bne a0, t1, ddr2_smc_check",
        "  j ddr2_ok",
        "ddr2_smc_check:",
        "  # 上面用 a0=7 覆盖了返回值，修正为独立寄存 t2 保存结果",
        "  j ddr2_ok",
    ]

    # Fix 1D register allocation cleanly (save SMC result in t5 before loading error code)
    idx_1d = lines.index("  li t1, 142")
    lines[idx_1d:] = [
        "  mv t5, a0",
        "  li t1, 142",
        "  li a0, 7",
        "  bne t5, t1, ddr2_fail",
        "ddr2_ok:",
        "  li a0, str_pass",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s10)",
        "ddr2_fail:",
        "  mv s5, a0",
        "  li a0, str_fail",
        "  jal ra, uart_puts",
        "  mv a0, s5",
        "  jal ra, uart_puthex",
        "  li a0, str_nl",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s10)",
        "",
        "# ======================================================================",
        "# [2/5] CPU 性能计数 + L0D Load-Use + 100 MHz / 1 MHz CLINT 互证基准",
        "# ======================================================================",
        "test_bench:",
        "  mv s10, ra",
        "  li a0, str_t2",
        "  jal ra, uart_puts",
        "  li t6, 0x0200BFF8       # CLINT_MTIME_L (1 MHz)",
        "  li t5, 0x80001000       # L0D 热地址",
        "  li t0, 0x00000001",
        "  sw t0, 0(t5)",
        "  csrr s2, mcycle",
        "  csrr s3, minstret",
        "  lw s4, 0(t6)",
        "  li t1, 2000             # 2000 次循环 (含 L0D 命中、ALU 与分支预测)",
        "  li t2, 0",
        "bench_loop:",
        "  lw t3, 0(t5)",
        "  addi t1, t1, -1",
        "  add t2, t2, t3",
        "  bne t1, zero, bench_loop",
        "  csrr t0, mcycle",
        "  csrr t1, minstret",
        "  lw t4, 0(t6)",
        "  sub s2, t0, s2          # delta mcycle",
        "  sub s3, t1, s3          # delta minstret",
        "  sub s4, t4, s4          # delta mtime (us @ 1 MHz)",
        "  mv a0, s2",
        "  jal ra, uart_puthex",
        "  li a0, str_ins",
        "  jal ra, uart_puts",
        "  mv a0, s3",
        "  jal ra, uart_puthex",
        "  li a0, str_mt",
        "  jal ra, uart_puts",
        "  mv a0, s4",
        "  jal ra, uart_puthex",
        "  li a0, str_nl",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s10)",
        "",
        "# ======================================================================",
        "# [3/5] VGA (640x480 彩条确认) & [4/5] microSD SPI 卡槽检测",
        "# ======================================================================",
        "test_vga_sd:",
        "  mv s10, ra",
        "  li t5, 0x10002000       # VGA_BASE",
        "  li t0, 1                # EN=1, MODE=0 (8 色彩条)",
        "  sw t0, 0(t5)",
        "  lw s2, 12(t5)           # VGA_RES_ID (+0x0C = 0x028001E0)",
        "  lw s3, 4(t5)            # VGA_STAT (+0x04, [31:16]=frame_cnt)",
        "  srli s3, s3, 16",
        "  li a0, str_t3",
        "  jal ra, uart_puts",
        "  mv a0, s2",
        "  jal ra, uart_puthex",
        "  li a0, str_fr",
        "  jal ra, uart_puts",
        "  mv a0, s3",
        "  jal ra, uart_puthex",
        "  li a0, str_nl",
        "  jal ra, uart_puts",
        "",
        "  li a0, str_t4",
        "  jal ra, uart_puts",
        "  li t5, 0x10001000       # SPI_BASE",
        "  lw t0, 4(t5)            # SPI_STAT (+0x04, bit1 = SD_CD_N)",
        "  andi t0, t0, 2",
        "  bne t0, zero, sd_empty",
        "  li a0, str_sd_in",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s10)",
        "sd_empty:",
        "  li a0, str_sd_no",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s10)",
        "",
        "# ======================================================================",
        "# [5/5] OV5640 SCCB 芯片 ID 探测 (0x300A=0x56, 0x300B=0x40, 无卡不死等)",
        "# ======================================================================",
        "test_cam:",
        "  mv s10, ra",
        "  li a0, str_t5",
        "  jal ra, uart_puts",
        "  li s6, 0x10003000       # CAM_BASE",
        "  # 读 0x300A (Chip ID High)",
        "  li a0, 0x300A",
        "  jal ra, sccb_read_reg",
        "  bne a1, zero, cam_nack",
        "  mv s2, a0",
        "  # 读 0x300B (Chip ID Low)",
        "  li a0, 0x300B",
        "  jal ra, sccb_read_reg",
        "  bne a1, zero, cam_nack",
        "  slli s2, s2, 8",
        "  or s2, s2, a0           # 预期 0x00005640",
        "  li a0, str_cam_ok",
        "  jal ra, uart_puts",
        "  mv a0, s2",
        "  jal ra, uart_puthex",
        "  li a0, str_nl",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s10)",
        "cam_nack:",
        "  li a0, str_cam_no",
        "  jal ra, uart_puts",
        "  jalr zero, 0(s10)",
        "",
        "# sccb_read_reg(a0=reg16) -> a0=data8, a1=err(0=ok, 1=nack/timeout)",
        "sccb_read_reg:",
        "  sw a0, 8(s6)            # CAM_SCCB_OP (+0x08)",
        "  li t0, 0x0A             # CTRL: CAM_RST_N=1 (bit3), SCCB_RD=1 (bit1)",
        "  sw t0, 0(s6)",
        "  li t1, 200000           # 超时保护 (~2 ms @ 100 MHz)",
        "sccb_wait:",
        "  lw t2, 4(s6)            # CAM_STAT (+0x04): bit0=BUSY, bit1=NACK",
        "  andi t3, t2, 1",
        "  beq t3, zero, sccb_done",
        "  addi t1, t1, -1",
        "  bne t1, zero, sccb_wait",
        "  li a0, 0",
        "  li a1, 1",
        "  ret",
        "sccb_done:",
        "  andi a1, t2, 2          # bit1 = SCCB_NACK",
        "  lw a0, 12(s6)           # CAM_SCCB_RD (+0x0C)",
        "  andi a0, a0, 0xFF",
        "  ret",
        "",
        "# ======================================================================",
        "# UART 工具函数 (使用 s0=0x10000000, 仅破坏 t0-t4, a0)",
        "# ======================================================================",
        "uart_putc:",
        "  lw t0, 20(s0)           # LSR (+0x14)",
        "  andi t0, t0, 0x20       # bit5 = THRE",
        "  beq t0, zero, uart_putc",
        "  sw a0, 0(s0)            # THR (+0x00)",
        "  ret",
        "",
        "uart_puts:",
        "  mv t4, ra",
        "  mv t1, a0",
        "puts_loop:",
        "  lbu a0, 0(t1)",
        "  beq a0, zero, puts_done",
        "  jal ra, uart_putc",
        "  addi t1, t1, 1",
        "  j puts_loop",
        "puts_done:",
        "  jalr zero, 0(t4)",
        "",
        "uart_puthex:",
        "  mv t4, ra",
        "  mv t1, a0",
        "  li t2, 28",
        "hex_loop:",
        "  srl t3, t1, t2",
        "  andi t3, t3, 0xF",
        "  li a0, 10",
        "  blt t3, a0, hex_dig",
        "  addi a0, t3, 55         # 'A' - 10",
        "  j hex_emit",
        "hex_dig:",
        "  addi a0, t3, 48         # '0'",
        "hex_emit:",
        "  jal ra, uart_putc",
        "  addi t2, t2, -4",
        "  bge t2, zero, hex_loop",
        "  jalr zero, 0(t4)",
        "",
        "# ======================================================================",
        "# 只读数据表 (128 MB DDR2 跨区探测地址 + 字符串池)",
        "# ======================================================================",
        ".align 2",
        "ddr_span_tbl:",
        "  .word 0x80000000",
        "  .word 0x80004004",
        "  .word 0x80100008",
        "  .word 0x8100000C",
        "  .word 0x82000010",
        "  .word 0x84000014",
        "  .word 0x86000018",
        "  .word 0x87FFF01C",
    ]

    # Append 4-byte aligned null-terminated ASCII strings as .word entries
    for label, text in strings.items():
        raw = text.encode("ascii") + b"\x00"
        while len(raw) % 4 != 0:
            raw += b"\x00"
        lines.append(f"{label}:")
        for i in range(0, len(raw), 4):
            w = raw[i] | (raw[i + 1] << 8) | (raw[i + 2] << 16) | (raw[i + 3] << 24)
            lines.append(f"  .word 0x{w:08x}")

    return "\n".join(lines) + "\n"


def main() -> int:
    src_file = HERE / "board_bist.S"
    hex_file = HERE / "board_bist.hex"

    src = build_asm_source()
    src_file.write_text(src, encoding="utf-8")

    # Assemble with TEXT_BASE = 0x00001000 (BootROM base)
    asm.TEXT_BASE = BOOTROM_BASE
    raw_hex = HERE / "_board_bist_raw.hex"
    old_argv = sys.argv
    try:
        sys.argv = ["asm.py", str(src_file), "-o", str(raw_hex)]
        rc = asm.main()
        if rc != 0:
            return rc
    finally:
        sys.argv = old_argv

    words = [ln.strip() for ln in raw_hex.read_text(encoding="ascii").splitlines() if ln.strip()]
    raw_hex.unlink(missing_ok=True)

    if len(words) > BOOTROM_WORDS:
        raise RuntimeError(f"BootROM image too large: {len(words)} > {BOOTROM_WORDS} words")

    used = len(words)
    # Pad to exact 4,096 words (16 KB) so Vivado $readmemh emits zero size warnings
    words.extend([f"{NOP_WORD:08x}"] * (BOOTROM_WORDS - used))
    hex_file.write_text("\n".join(words) + "\n", encoding="ascii")
    print(f"[board_bist] Built {hex_file} ({used} active words / {used * 4} bytes, padded to {BOOTROM_WORDS} words)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
